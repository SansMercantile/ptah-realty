export function getInfrastructureByCategory(category: InfrastructureCategory | 'ALL'): InfrastructureItem[] {
  if (category === 'ALL') return INFRASTRUCTURE_DATA;
  return INFRASTRUCTURE_DATA.filter(item => item.category === category);
}

export function searchInfrastructure(query: string, maxRadiusMeters: number = 5000): InfrastructureItem[] {
  let list = INFRASTRUCTURE_DATA.filter(item => item.distanceMeters <= maxRadiusMeters);
  if (!query) return list;
  const q = query.toLowerCase().trim();
  return list.filter(item => 
    item.name.toLowerCase().includes(q) ||
    item.type.toLowerCase().includes(q) ||
    item.suburb.toLowerCase().includes(q) ||
    item.tags.some(t => t.toLowerCase().includes(q))
  );
}
